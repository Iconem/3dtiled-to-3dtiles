// Ported as pure functions from viewer.html's buildMiddlewareUrl/streamParams/assetUrl/srcUrl
// (lines ~694-797) — same algorithms, but read an explicit params object instead of globals.
import { MW, SDATA, FORMATS, DIRECT, TOOLS_DATASETS, PSEUDO_FORMATS, fmtMeta, canCentroids, type Asset, type AssetType, type FormatMeta } from './formats';

export type TilesetOp = 'implicit-to-explicit' | 'upgrade' | '';

export type ViewerMode = 'stream' | 'offline' | 'tools';
export type CacheScope = 'none' | 'hierarchy' | 'all';
export type TilingMode = 'implicit' | 'explicit';
export type ToolName = 'implicit-to-explicit' | 'upgrade' | 'packages';

export const isRemoteUrl = (s: string) => /^https?:\/\//i.test(s);
export const srcUrl = (s: string) => (isRemoteUrl(s) ? s : `${SDATA}/${s}`);

export interface MiddlewareParams {
  selectedFormat: string;
  viewerMode: ViewerMode;
  cacheScope: CacheScope;
  prefetchN: number;
  transformOp: string;
  centroidsOnly: boolean;
  tilingMode: TilingMode;
}

export function streamParams(f: FormatMeta | undefined, p: Pick<MiddlewareParams, 'tilingMode' | 'centroidsOnly' | 'selectedFormat'>) {
  let q = f?.octree ? `&tiling=${p.tilingMode}` : '';
  if (canCentroids(p.selectedFormat) && p.centroidsOnly) q += '&centroids=1';
  return q;
}

export function buildMiddlewareUrl(rawSrc: string, p: MiddlewareParams, fOverride?: FormatMeta) {
  const f = fOverride ?? fmtMeta(p.selectedFormat);
  const fmt = f ? f.fmt : p.selectedFormat;
  const enc = encodeURIComponent(rawSrc);
  if (p.cacheScope === 'all') return `${MW}/convert/tileset.json?format=${fmt}&url=${enc}${streamParams(f, p)}`;
  let q = `&cache=${p.cacheScope}`;
  if (p.cacheScope === 'none') q += `&prefetch=${p.prefetchN}`;
  if (p.transformOp) q += `&transform=${p.transformOp}`;
  return `${MW}/stream/tileset.json?format=${fmt}&url=${enc}${q}${streamParams(f, p)}`;
}

export function assetUrl(f: FormatMeta, a: Asset, p: MiddlewareParams): string | null {
  if (p.viewerMode === 'offline') {
    if (!a.out) return null;
    return `${SDATA}/${a.out}/tileset.json`;
  }
  if (p.viewerMode === 'stream') {
    if (!f.stream) return null;
    const rawSrc = srcUrl(p.cacheScope === 'all' ? a.src! : (a.streamSrc ?? a.src!));
    return buildMiddlewareUrl(rawSrc, p, f);
  }
  return null;
}

export interface Preset {
  id: string;
  label: string;
  type: AssetType;
  url: string | null;
  rawSrc?: string;
  custom?: boolean;
  octree?: boolean;
  flyTo?: { lon: number; lat: number; height: number };
  /** Only offer this preset when the tile-server reports this aggregate set (see useAvailableSets). */
  requiresSet?: string;
}

/** Ported from viewer.html's currentPresets() — the asset-pill list for the current mode/format. */
export function currentPresets(p: MiddlewareParams & { toolName: ToolName; tilesetOp?: TilesetOp }): Preset[] {
  if (p.viewerMode === 'tools') {
    return (TOOLS_DATASETS[p.toolName] || []).map((a) => ({
      id: `tool-${p.toolName}-${a.id}`,
      label: a.label,
      type: a.type!,
      url:
        p.toolName === 'packages'
          ? `${MW}/3dtiles-self-contained/tileset.json?url=${encodeURIComponent(a.pkg!)}`
          : `${MW}/3dtiles-tools/tileset.json?tool=${encodeURIComponent(p.toolName)}&url=${encodeURIComponent(a.url!)}`,
    }));
  }
  if (p.selectedFormat === '3dtiles') {
    // Whole-tileset rewrite (implicit→explicit / legacy b3dm→1.1 upgrade) via the SAME generic
    // /3dtiles-tools endpoint the "Tools" mode pills already use — it already accepts an arbitrary
    // `url=`, not just the two hardcoded Tools presets, so any DIRECT tileset can be run through it.
    const wrap = (u: string) => (p.tilesetOp ? `${MW}/3dtiles-tools/tileset.json?tool=${p.tilesetOp}&url=${encodeURIComponent(u)}` : u);
    return DIRECT.map((d) => ({ id: d.id, label: `${d.icon} ${d.label}`, type: d.type, url: wrap(d.url) }));
  }
  if (p.selectedFormat === 'packages') {
    return (TOOLS_DATASETS['packages'] || []).map((a) => ({
      id: `fmt-pkg-${a.id}`,
      label: `📦 ${a.label}`,
      type: a.type!,
      url: `${MW}/stream/tileset.json?format=${a.pkg!.toLowerCase().endsWith('.3tz') ? '3tz' : '3dtiles-pkg'}&url=${encodeURIComponent(a.pkg!)}`,
    }));
  }
  if (p.selectedFormat === 'aggregate') {
    // /aggregate mosaics: one 3D Tiles endpoint over many datasets (see docs "Meta-tilesets").
    // `demo` sets are committed on the server; `iconem` is a machine-local set generated by
    // scripts/iconem-share-links.mjs. Mixed and point-cloud variants are typed `pointcloud` so the
    // point-size control reaches their points; meshes are unaffected by it.
    const agg = (q: string) => `${MW}/aggregate/tileset.json?${q}`;
    // Close enough that site-sized children pass their geometric-error gate and actually load — from
    // the park-wide altitude nothing is fetched (that is the mosaic working), which reads as "empty".
    const ANGKOR_THOM = { lon: 103.8590, lat: 13.4412, height: 1_800 };
    return [
      { id: 'agg-world', label: '🧩 World — open data + Angkor + Aerometrex + Vexcel', type: 'mesh', url: agg('set=world&nest=geodetic') },
      { id: 'agg-opendata', label: '🧩 Open data — 10 cities', type: 'mesh', url: agg('set=opendata&nest=geodetic'), flyTo: { lon: 4.8, lat: 47.5, height: 1_800_000 } },
      // Group volumes are the quadtree cells by default (debug tiles show the 2×1 geodetic grid); the
      // picker's "bounds" control switches to fitted spheres, regions or ENU boxes (see docs: bv=).
      { id: 'agg-angkor', label: '🧩 Angkor — 23 sites (geodetic cells)', type: 'mesh', url: agg('set=angkor&nest=geodetic'), flyTo: ANGKOR_THOM },
      { id: 'agg-angkor-sphere', label: '🧩 Angkor — 23 sites (spheres)', type: 'mesh', url: agg('set=angkor&nest=geodetic&bv=sphere'), flyTo: ANGKOR_THOM },
      { id: 'agg-angkor-region', label: '🧩 Angkor — 23 sites (regions)', type: 'mesh', url: agg('set=angkor&nest=geodetic&bv=region'), flyTo: ANGKOR_THOM },
      { id: 'agg-angkor-box', label: '🧩 Angkor — 23 sites (boxes)', type: 'mesh', url: agg('set=angkor&nest=geodetic&bv=box'), flyTo: ANGKOR_THOM },
      { id: 'agg-angkor-merc', label: '🧩 Angkor — 23 sites (mercator)', type: 'mesh', url: agg('set=angkor&nest=mercator'), flyTo: ANGKOR_THOM },
      { id: 'agg-phnomkulen', label: '🧩 Angkor — only PhnomKulen', type: 'mesh', url: agg('set=angkor&only=PhnomKulen'), flyTo: { lon: 104.0, lat: 13.55, height: 12_000 } },
      // Committed public sets (packages/tile-server/aggregate-sets/): flai's national open LiDAR as COPC
      // overviews (CRS passed per entry), and Aerometrex's US city previews through the tileset-aware /proxy.
      { id: 'agg-flai', label: '🧩 flai open LiDAR — 113 national COPC', type: 'pointcloud', url: agg('set=flai&nest=geodetic'), flyTo: { lon: 10, lat: 54, height: 3_500_000 } },
      // Vexcel needs VEXCEL_API_KEY on the server (the proxy adds it), so it only shows where that is set.
      { id: 'agg-vexcel', label: '🧩 Vexcel — 10 Australian cities (proxied)', type: 'mesh', url: agg('set=vexcel&nest=geodetic'), flyTo: { lon: 153.43, lat: -28.0, height: 6_000 }, requiresSet: 'vexcel' },
      { id: 'agg-aerometrex', label: '🧩 Aerometrex — 12 US cities (proxied)', type: 'mesh', url: agg('set=aerometrex&nest=geodetic'), flyTo: { lon: -73.982, lat: 40.685, height: 7_000 } },
      // `iconem` is a machine-local set (a gitignored manifest of share links), so these four only
      // appear where the server actually has it — see TopBar's requiresSet filter.
      { id: 'agg-iconem-all', label: '🧩 Iconem — all formats', type: 'pointcloud', url: agg('set=iconem&nest=geodetic'), requiresSet: 'iconem' },
      { id: 'agg-iconem-3dtiles', label: '🧩 Iconem — 3D Tiles only', type: 'mesh', url: agg('set=iconem&format=3dtiles&nest=geodetic'), requiresSet: 'iconem' },
      { id: 'agg-iconem-potree', label: '🧩 Iconem — Potree only', type: 'pointcloud', url: agg('set=iconem&format=potree&nest=geodetic'), requiresSet: 'iconem' },
      // Diachronic sites (Mes Aynak 2010→2022, Mosul 2018→2020…) show their newest capture only.
      { id: 'agg-iconem-latest', label: '🧩 Iconem — latest captures (Mes Aynak)', type: 'pointcloud', url: agg('set=iconem&nest=geodetic&latest=1'), flyTo: { lon: 69.3080, lat: 34.2698, height: 9_000 }, requiresSet: 'iconem' },
      // Every Mes Aynak capture, each put on the ground on its own (server-side &snap=).
      { id: 'agg-iconem-mesaynak', label: '🧩 Iconem — Mes Aynak, all years, snapped', type: 'pointcloud', url: agg('set=iconem&only=MesAynak&snap=1'), flyTo: { lon: 69.3080, lat: 34.2698, height: 5_500 }, requiresSet: 'iconem' },
      { id: 'agg-iconem-copc', label: '🧩 Iconem — COPC only', type: 'pointcloud', url: agg('set=iconem&format=copc&nest=geodetic'), requiresSet: 'iconem' },
    ];
  }
  if (p.selectedFormat === 'bing') {
    const bingUrl = `${MW}/bing/tileset.json?g=15530`;
    return [
      { id: 'bing-world', label: '🗺 Bing 3D — world (td1)', type: 'mesh', url: bingUrl },
      { id: 'bing-roma', label: '🗺 Bing 3D — Roma', type: 'mesh', url: bingUrl, flyTo: { lon: 12.4924, lat: 41.8902, height: 1200 } },
      { id: 'bing-washington', label: '🗺 Bing 3D — Washington', type: 'mesh', url: bingUrl, flyTo: { lon: -77.0353, lat: 38.8895, height: 1600 } },
      { id: 'bing-berlin', label: '🗺 Bing 3D — Berlin', type: 'mesh', url: bingUrl, flyTo: { lon: 13.3777, lat: 52.5163, height: 1200 } },
    ];
  }
  if (p.selectedFormat === 'threemx') {
    const tmx = (mdl: string) => `${MW}/stream/tileset.json?format=threemx&url=${encodeURIComponent(mdl)}`;
    // rawSrc = the actual .3mx/.3mxb source, NOT the MW-wrapped url — without it, toggling "raw url"
    // ON has nothing to switch the field to and silently keeps showing the wrapped middleware URL.
    return [
      { id: '3mx-tende', label: '🏛 Tende village (dept06, colormap)', type: 'mesh', url: tmx('https://3d.departement06.fr/3mx/2019_07_Village_Tende_Resolution/Scene/2019_07_Village_Tende_Resolution.3mx'), rawSrc: 'https://3d.departement06.fr/3mx/2019_07_Village_Tende_Resolution/Scene/2019_07_Village_Tende_Resolution.3mx' },
      { id: '3mx-byu', label: '🏛 BYU Athletic (RGB)', type: 'mesh', url: tmx('https://campusmodel.groups.et.byu.net/Athletic_Buildings_3MX/Scene/Athletic_Buildings_3MX.3mx'), rawSrc: 'https://campusmodel.groups.et.byu.net/Athletic_Buildings_3MX/Scene/Athletic_Buildings_3MX.3mx' },
      { id: '3mx-chapelle', label: '🏛 Chapelle (scanit, .3mxb)', type: 'mesh', url: tmx('https://www.scanit-alsace.fr/PARTAGE/CHAPELLE/Scene/Data/MESH.3mxb'), rawSrc: 'https://www.scanit-alsace.fr/PARTAGE/CHAPELLE/Scene/Data/MESH.3mxb' },
    ];
  }
  if (p.selectedFormat === 'geosplats') {
    const gs = (mdl: string) => `${MW}/stream/tileset.json?format=geosplats&url=${encodeURIComponent(mdl)}&lod=5`;
    // Same rawSrc fix as threemx above — the raw source is the MapTiler splats model.json URL.
    return [
      { id: 'gs-1', label: '✨ Jastrzębia Góra, Poland', type: 'splat', url: gs('https://api.maptiler.com/splats/019e67bf-b89b-743d-91dd-79f7f4b4bd4e/model.json?key=GKF1QdQ4MpjgqtKiQuxR'), rawSrc: 'https://api.maptiler.com/splats/019e67bf-b89b-743d-91dd-79f7f4b4bd4e/model.json?key=GKF1QdQ4MpjgqtKiQuxR' },
      { id: 'gs-2', label: '✨ Baltimore Hotel Miami', type: 'splat', url: gs('https://api.maptiler.com/splats/019e5ff3-e23b-7063-bed2-c385d3e96d99/model.json?key=mNLmXyaTH4gRlwJHSYWp'), rawSrc: 'https://api.maptiler.com/splats/019e5ff3-e23b-7063-bed2-c385d3e96d99/model.json?key=mNLmXyaTH4gRlwJHSYWp' },
    ];
  }
  const f = fmtMeta(p.selectedFormat);
  if (!f) return [];
  const pills: Preset[] = f.assets
    .map((a) => ({
      id: `${f.fmt}-${a.id}`,
      label: `${f.icon} ${a.label}`,
      type: a.type ?? f.type,
      url: assetUrl(f, a, p),
      octree: f.octree,
      rawSrc: srcUrl(a.streamSrc ?? a.src!),
    }))
    .filter((pr) => pr.url);
  pills.push({ id: `${f.fmt}-custom`, label: `${f.icon} ✎ custom url`, type: f.type, url: '__custom__', custom: true, octree: f.octree });
  return pills;
}

