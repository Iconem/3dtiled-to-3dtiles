/**
 * build-3dtr-master.mjs — build 3DTilesRendererJS from source so the viewer can run against unreleased
 * work (the point-cloud effects of #1742, traversal fixes, …) before it reaches npm.
 *
 *   node scripts/build-3dtr-master.mjs [--ref=<branch|sha>]     → .local/3DTilesRendererJS/build/
 *   cd apps/viewer && npm run dev:3dtr-master                     → viewer on that build
 *
 * Nothing tracked changes: the clone lives in the gitignored .local/, the lockfile keeps 0.5.2, and
 * switching back is just `npm run dev`. When a release ships the work, bump the dependency and delete
 * the clone.
 *
 * Windows: upstream's lib config marks a module external unless it starts with . / or \ — its own
 * path.resolve()d aliases are `C:\…`, so on Windows every internal import was externalised and
 * build/index.js came out as a 253-byte file of mangled re-exports. The wrapper written below only
 * widens that test to absolute paths; upstream files are untouched.
 */
import { execSync } from 'node:child_process';
import { existsSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const LOCAL = fileURLToPath(new URL('../.local/', import.meta.url));
const DIR = path.join(LOCAL, '3DTilesRendererJS');
const ref = (process.argv.find((a) => a.startsWith('--ref=')) || '--ref=master').slice(6);
const run = (cmd, cwd = DIR) => { console.log(`$ ${cmd}`); execSync(cmd, { cwd, stdio: 'inherit' }); };

if (!existsSync(DIR)) run(`git clone https://github.com/NASA-AMMOS/3DTilesRendererJS "${DIR}"`, LOCAL);
run('git fetch --quiet origin');
run(`git checkout --quiet ${ref}`);
if (/^[\w./-]+$/.test(ref) && !/^[0-9a-f]{7,40}$/.test(ref)) run(`git pull --quiet --ff-only origin ${ref}`);
run('npm ci --no-audit --no-fund');

const wrapper = path.join(LOCAL, '3dtr-vite.lib-config.win.mjs');
writeFileSync(wrapper, `// generated by scripts/build-3dtr-master.mjs — see its header
import path from 'node:path';
import base from './3DTilesRendererJS/vite.lib-config.js';
export default (env) => {
  const config = base(env);
  config.build.rollupOptions.external = (p) => !/^[./\\\\]/.test(p) && !path.isAbsolute(p) && !/^3d-tiles-renderer/.test(p);
  return config;
};
`);
run(`npx vite build --config "${wrapper}"`);

const index = path.join(DIR, 'build', 'index.js');
if (!existsSync(index) || statSync(index).size < 1000) {
  console.error(`build/index.js is missing or ${existsSync(index) ? statSync(index).size : 0} bytes — the external-module fix did not apply`);
  process.exit(1);
}
const head = execSync('git log -1 --format="%h %cd %s" --date=short', { cwd: DIR }).toString().trim();
console.log(`\n3DTilesRendererJS ${head}\nbuilt → ${path.relative(process.cwd(), path.join(DIR, 'build'))}\nrun:   cd apps/viewer && npm run dev:3dtr-master`);
